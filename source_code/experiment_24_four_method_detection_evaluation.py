# SENSOR-FILE DISCOVERY
# =============================================================================

def find_individual_sensor_file(
    method: str,
    network: str,
    seed: int,
) -> Path | None:
    """
    Search for an individual sensor-selection CSV.
    """

    search_directories = METHOD_SENSOR_PATHS[method]

    filenames = [
        "evaluation_selected_sensors.csv",
        "selected_sensors.csv",
        "sensors.csv",
    ]

    for base in search_directories:

        if not base.exists():
            continue

        # -------------------------------------------------------------
        # Known directory layouts
        # -------------------------------------------------------------

        for filename in filenames:

            candidates = [

                base
                / network
                / f"seed_{seed}"
                / filename,

                base
                / network
                / f"seed-{seed}"
                / filename,

                base
                / f"{network}_seed_{seed}"
                / filename,

                base
                / f"{network}_seed_{seed}_{filename}",
            ]

            for candidate in candidates:

                if candidate.exists():

                    return candidate

        # -------------------------------------------------------------
        # Recursive fallback
        # -------------------------------------------------------------

        for filename in filenames:

            for candidate in base.rglob(filename):

                text = str(candidate).lower()

                if (
                    network.lower() in text
                    and
                    f"seed_{seed}".lower() in text
                ):

                    return candidate

    return None


# =============================================================================
# COVERAGE-CSV DISCOVERY
# =============================================================================

def find_coverage_result_file(
    method: str,
) -> list[Path]:
    """
    Find coverage seed-result CSV files for the specified method.
    """

    files = []

    for base in METHOD_SENSOR_PATHS[method]:

        if not base.exists():
            continue

        patterns = [
            "*coverage*seed*results*.csv",
            "*coverage*seed*result*.csv",
            "*coverage_seed_results.csv",
        ]

        for pattern in patterns:

            files.extend(
                base.rglob(pattern)
            )

    # Preserve order while removing duplicates.
    unique_files = []

    seen = set()

    for path in files:

        resolved = str(path.resolve())

        if resolved not in seen:

            seen.add(resolved)
            unique_files.append(path)

    return unique_files


# =============================================================================
# SENSOR LIST PARSING
# =============================================================================

def parse_sensor_list(value) -> list[str]:
    """
    Convert common CSV representations of sensor lists into a Python list.

    Supported forms include:

        ['101', '203', '255', '103', '109']

        ["101", "203", "255", "103", "109"]

        101|203|255|103|109

        101,203,255,103,109
    """

    if pd.isna(value):
        return []

    text = str(value).strip()

    if not text:
        return []

    # -------------------------------------------------------------
    # Python-list representation
    # -------------------------------------------------------------

    if (
        text.startswith("[")
        and
        text.endswith("]")
    ):

        try:

            parsed = ast.literal_eval(
                text
            )

            if isinstance(
                parsed,
                (list, tuple)
            ):

                sensors = [
                    normalise_node_id(v)
                    for v in parsed
                ]

            else:

                sensors = [
                    normalise_node_id(parsed)
                ]

        except Exception:

            cleaned = text[1:-1]

            sensors = [
                normalise_node_id(v)
                for v in cleaned.split(",")
            ]

    # -------------------------------------------------------------
    # Pipe-separated
    # -------------------------------------------------------------

    elif "|" in text:

        sensors = [
            normalise_node_id(v)
            for v in text.split("|")
        ]

    # -------------------------------------------------------------
    # Semicolon-separated
    # -------------------------------------------------------------

    elif ";" in text:

        sensors = [
            normalise_node_id(v)
            for v in text.split(";")
        ]

    # -------------------------------------------------------------
    # Comma-separated
    # -------------------------------------------------------------

    elif "," in text:

        sensors = [
            normalise_node_id(v)
            for v in text.split(",")
        ]

    else:

        sensors = [
            normalise_node_id(text)
        ]

    # Remove empty values and duplicates.
    sensors = [
        sensor
        for sensor in sensors
        if sensor
    ]

    sensors = list(
        dict.fromkeys(sensors)
    )

    return sensors


# =============================================================================
# LOAD SENSORS FROM INDIVIDUAL CSV
# =============================================================================

def load_sensors_from_individual_file(
    path: Path,
) -> list[str]:

    df = pd.read_csv(path)

    possible_columns = [
        "node_id",
        "node",
        "sensor",
        "sensor_id",
        "nodeID",
    ]

    node_column = None

    for column in possible_columns:

        if column in df.columns:

            node_column = column
            break

    if node_column is None:

        raise ValueError(
            "\n"
            f"Sensor-selection file has no recognised "
            f"node-ID column:\n{path}\n"
            f"Columns found: {list(df.columns)}"
        )

    sensors = [
        normalise_node_id(v)
        for v in df[node_column].tolist()
        if normalise_node_id(v)
    ]

    sensors = list(
        dict.fromkeys(sensors)
    )

    return sensors


# =============================================================================
# LOAD SENSORS FROM COVERAGE RESULT CSV
# =============================================================================

def load_sensors_from_coverage_file(
    path: Path,
    network: str,
    seed: int,
) -> list[str] | None:

    try:

        df = pd.read_csv(path)

    except Exception:

        return None

    columns_lower = {
        str(column).strip().lower(): column
        for column in df.columns
    }

    network_column = columns_lower.get(
        "network"
    )

    seed_column = columns_lower.get(
        "seed"
    )

    sensor_column = None

    for candidate in [
        "selected_sensors",
        "selected_sensor",
        "sensors",
        "sensor_nodes",
        "sensor_list",
    ]:

        if candidate in columns_lower:

            sensor_column = columns_lower[
                candidate
            ]

            break

    if (
        network_column is None
        or
        seed_column is None
        or
        sensor_column is None
    ):

        return None

    # -------------------------------------------------------------
    # Filter network and seed
    # -------------------------------------------------------------

    seed_values = pd.to_numeric(
        df[seed_column],
        errors="coerce",
    )

    subset = df[
        (
            df[network_column]
            .astype(str)
            .str.strip()
            ==
            str(network).strip()
        )
        &
        (
            seed_values
            ==
            seed
        )
    ]

    if subset.empty:
        return None

    # -------------------------------------------------------------
    # If several radii are present, we only need one sensor list.
    # Sensor configuration is independent of radius.
    # -------------------------------------------------------------

    value = subset.iloc[0][
        sensor_column
    ]

    sensors = parse_sensor_list(
        value
    )

    if not sensors:
        return None

    return sensors


# =============================================================================
# MAIN SENSOR LOADER
# =============================================================================

def load_sensor_selection(
    method: str,
    network: str,
    seed: int,
) -> list[str]:

    # -------------------------------------------------------------------------
    # FIRST: individual sensor-selection file
    # -------------------------------------------------------------------------

    individual_file = find_individual_sensor_file(
        method,
        network,
        seed,
    )

    if individual_file is not None:

        sensors = load_sensors_from_individual_file(
            individual_file
        )

        print(
            f"      Sensor source: "
            f"{individual_file}"
        )

    # -------------------------------------------------------------------------
    # SECOND: coverage result CSV
    # -------------------------------------------------------------------------

    else:

        coverage_files = find_coverage_result_file(
            method
        )

        sensors = None
        selected_file = None

        for coverage_file in coverage_files:

            candidate_sensors = (
                load_sensors_from_coverage_file(
                    coverage_file,
                    network,
                    seed,
                )
            )

            if candidate_sensors:

                sensors = candidate_sensors
                selected_file = coverage_file
                break

        if sensors is None:

            searched = "\n".join(
                str(path)
                for path in METHOD_SENSOR_PATHS[method]
            )

            raise FileNotFoundError(
                "\n"
                "Could not locate final sensor-selection information.\n"
                f"Method: {method}\n"
                f"Network: {network}\n"
                f"Seed: {seed}\n\n"
                f"Searched directories:\n{searched}\n"
            )

        print(
            f"      Sensor source: "
            f"{selected_file}"
        )

    # -------------------------------------------------------------------------
    # Remove duplicates while preserving order.
    # -------------------------------------------------------------------------

    sensors = list(
        dict.fromkeys(
            sensors
        )
    )

    if len(sensors) == 0:

        raise ValueError(
            f"No sensors found for "
            f"{method}, {network}, seed {seed}."
        )

    if len(sensors) != SENSOR_BUDGET:

        print(
            f"      WARNING: {method} {network} "
            f"seed {seed} has {len(sensors)} sensors; "
            f"expected {SENSOR_BUDGET}."
        )

    return sensors[:SENSOR_BUDGET]


# =============================================================================
# COMMON SCENARIO GENERATION
# =============================================================================

def create_common_scenarios(
    graph: nx.Graph,
    network: str,
) -> dict:

    """
    Create one deterministic set of leak and contamination event nodes.

    IMPORTANT:
        The same event locations are subsequently used for every algorithm
        on this network.
    """

    nodes = sorted(
        normalise_node_id(node)
        for node in graph.nodes()
    )

    if len(nodes) < 10:

        raise RuntimeError(
            f"{network} has too few nodes for scenario generation."
        )

    # Network-specific but deterministic RNG.
    network_offset = sum(
        ord(character)
        for character in network
    )

    rng = np.random.default_rng(
        COMMON_SCENARIO_SEED
        + network_offset
    )

    leak_count = min(
        LEAK_SCENARIO_COUNT,
        len(nodes),
    )

    contamination_count = min(
        CONTAMINATION_SCENARIO_COUNT,
        len(nodes),
    )

    leak_nodes = list(
        rng.choice(
            nodes,
            size=leak_count,
            replace=False,
        )
    )

    contamination_nodes = list(
        rng.choice(
            nodes,
            size=contamination_count,
            replace=False,
        )
    )

    return {
        "leak_nodes": leak_nodes,
        "contamination_nodes": contamination_nodes,
    }


# =============================================================================
# SHORTEST DISTANCE
# =============================================================================

def nearest_sensor_distance(
    graph: nx.Graph,
    event_node: str,
    sensors: list[str],
) -> float:

    event_node = normalise_node_id(
        event_node
    )

    if event_node not in graph:
        return math.inf

    distances = []

    for sensor in sensors:

        sensor = normalise_node_id(
            sensor
        )

        if sensor not in graph:
            continue

        try:

            distance = nx.shortest_path_length(
                graph,
                source=event_node,
                target=sensor,
            )

            distances.append(
                distance
            )

        except nx.NetworkXNoPath:

            continue

    if not distances:
        return math.inf

    return float(
        min(distances)
    )


# =============================================================================
# EVENT DETECTION
# =============================================================================

def evaluate_event_detection(
    graph: nx.Graph,
    sensors: list[str],
    event_nodes: list[str],
    radius: int,
):
    """
    Detect an event when at least one selected sensor is within the specified
    graph-hop radius.
    """

    if not event_nodes:

        return (
            0.0,
            0,
            0,
            math.nan,
        )

    detected = 0
    distances = []

    for event_node in event_nodes:

        distance = nearest_sensor_distance(
            graph,
            event_node,
            sensors,
        )

        distances.append(
            distance
        )

        if distance <= radius:
            detected += 1

    total_events = len(
        event_nodes
    )

    detection_percent = (
        100.0
        * detected
        / total_events
    )

    finite_distances = [
        distance
        for distance in distances
        if np.isfinite(distance)
    ]

    if finite_distances:

        mean_distance = float(
            np.mean(
                finite_distances
            )
        )

    else:

        mean_distance = math.nan

    return (
        detection_percent,
        detected,
        total_events,
        mean_distance,
    )


# =============================================================================
# SPATIAL COVERAGE
# =============================================================================

def calculate_coverage(
    graph: nx.Graph,
    sensors: list[str],
    radius: int,
):

    all_nodes = set(
        graph.nodes()
    )

    covered_nodes = set()

    for sensor in sensors:

        sensor = normalise_node_id(
            sensor
        )

        if sensor not in graph:
            continue

        try:

            neighbourhood = (
                nx.single_source_shortest_path_length(
                    graph,
                    sensor,
                    cutoff=radius,
                )
            )

            covered_nodes.update(
                neighbourhood.keys()
            )

        except Exception:

            continue

    total_nodes = len(
        all_nodes
    )

    covered_count = len(
        covered_nodes
    )

    if total_nodes == 0:

        coverage_percent = 0.0

    else:

        coverage_percent = (
            100.0
            * covered_count
            / total_nodes
        )

    return (
        coverage_percent,
        covered_count,
        total_nodes,
    )


# =============================================================================
# REDUNDANCY
# =============================================================================

def calculate_redundancy(
    graph: nx.Graph,
    sensors: list[str],
    radius: int,
) -> int:

    coverage_counts = {}

    for sensor in sensors:

        sensor = normalise_node_id(
            sensor
        )

        if sensor not in graph:
            continue

        try:

            neighbourhood = (
                nx.single_source_shortest_path_length(
                    graph,
                    sensor,
                    cutoff=radius,
                )
            )

            for node in neighbourhood:

                coverage_counts[node] = (
                    coverage_counts.get(
                        node,
                        0,
                    )
                    + 1
                )

        except Exception:

            continue

    redundancy = sum(
        max(
            0,
            count - 1,
        )
        for count in coverage_counts.values()
    )

    return int(
        redundancy
    )


# =============================================================================
# COST
# =============================================================================

def calculate_deployment_cost(
    sensor_count: int,
) -> float:

    return float(
        sensor_count
        * SENSOR_UNIT_COST
    )


# =============================================================================
# SINGLE METHOD/NETWORK/SEED EVALUATION
# =============================================================================

def evaluate_method_seed(
    method: str,
    network: str,
    seed: int,
    graph: nx.Graph,
    scenarios: dict,
) -> dict:

    start_time = time.perf_counter()

    sensors = load_sensor_selection(
        method,
        network,
        seed,
    )

    # -------------------------------------------------------------------------
    # Validate sensor IDs against network topology.
    # -------------------------------------------------------------------------

    valid_sensors = [
        sensor
        for sensor in sensors
        if sensor in graph
    ]

    missing_sensors = [
        sensor
        for sensor in sensors
        if sensor not in graph
    ]

    if missing_sensors:

        print(
            f"      WARNING: {method} {network} "
            f"seed {seed} contains node IDs not found "
            f"in topology: {missing_sensors}"
        )

    # -------------------------------------------------------------------------
    # Coverage
    # -------------------------------------------------------------------------

    (
        coverage_percent,
        covered_nodes,
        total_nodes,
    ) = calculate_coverage(
        graph,
        valid_sensors,
        DETECTION_RADIUS,
    )

    # -------------------------------------------------------------------------
    # Leak detection
    # -------------------------------------------------------------------------

    (
        leak_detection_percent,
        detected_leaks,
        total_leaks,
        mean_leak_distance,
    ) = evaluate_event_detection(
        graph,
        valid_sensors,
        scenarios["leak_nodes"],
        DETECTION_RADIUS,
    )

    # -------------------------------------------------------------------------
    # Contamination detection
    # -------------------------------------------------------------------------

    (
        contamination_detection_percent,
        detected_contamination,
        total_contamination,
        mean_contamination_distance,
    ) = evaluate_event_detection(
        graph,
        valid_sensors,
        scenarios["contamination_nodes"],
        DETECTION_RADIUS,
    )

    # -------------------------------------------------------------------------
    # Redundancy
    # -------------------------------------------------------------------------

    redundancy = calculate_redundancy(
        graph,
        valid_sensors,
        DETECTION_RADIUS,
    )

    # -------------------------------------------------------------------------
    # Cost
    # -------------------------------------------------------------------------

    sensor_count = len(
        sensors
    )

    deployment_cost = (
        calculate_deployment_cost(
            sensor_count
        )
    )

    elapsed_time = (
        time.perf_counter()
        - start_time
    )

    # -------------------------------------------------------------------------
    # Return complete record
    # -------------------------------------------------------------------------

