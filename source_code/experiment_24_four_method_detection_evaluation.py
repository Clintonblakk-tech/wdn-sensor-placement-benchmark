def locate_network_file(network: str) -> Path | None:
    """
    Search the project for the EPANET .inp file corresponding to a benchmark
    network.
    """

    preferred_directories = [
        PROJECT_ROOT / "data",
        PROJECT_ROOT / "data" / "raw",
        PROJECT_ROOT / "data" / "networks",
        PROJECT_ROOT / "networks",
        PROJECT_ROOT / "models",
        PROJECT_ROOT / "src",
    ]

    preferred_names = [
        f"{network}.inp",
        f"{network.lower()}.inp",
        f"{network.upper()}.inp",
    ]

    # First check common directories.
    for directory in preferred_directories:

        if not directory.exists():
            continue

        for name in preferred_names:

            path = directory / name

            if path.exists():
                return path

    # Recursive fallback.
    for path in PROJECT_ROOT.rglob("*.inp"):

        if path.stem.lower() == network.lower():
            return path

    return None


# =============================================================================
# EPANET GRAPH PARSER
# =============================================================================

def load_network_graph(network: str):
    """
    Read the EPANET network topology and create an undirected NetworkX graph.

    The graph is used for the spatial hop-distance detection calculation.
    """

    inp_path = locate_network_file(network)

    if inp_path is None:

        raise FileNotFoundError(
            "\n"
            f"Could not locate the EPANET input file for {network}.\n"
            f"Search root: {PROJECT_ROOT}\n"
        )

    graph = nx.Graph()

    section = None

    # Nodes that may exist without an explicit link.
    nodes = set()

    with open(
        inp_path,
        "r",
        encoding="utf-8",
        errors="ignore",
    ) as file:

        for raw_line in file:

            line = raw_line.strip()

            if not line:
                continue

            if line.startswith(";"):
                continue

            if line.startswith("[") and line.endswith("]"):

                section = line.upper()
                continue

            # -------------------------------------------------------------
            # Node sections
            # -------------------------------------------------------------

            if section in (
                "[JUNCTIONS]",
                "[RESERVOIRS]",
                "[TANKS]",
            ):

                parts = line.split()

                if parts:
                    nodes.add(
                        normalise_node_id(parts[0])
                    )

            # -------------------------------------------------------------
            # Link sections
            # -------------------------------------------------------------

            elif section in (
                "[PIPES]",
                "[PUMPS]",
                "[VALVES]",
            ):

                parts = line.split()

                if len(parts) >= 3:

                    node_1 = normalise_node_id(
                        parts[1]
                    )

                    node_2 = normalise_node_id(
                        parts[2]
                    )

                    if node_1 and node_2:

                        graph.add_edge(
                            node_1,
                            node_2,
                        )

    graph.add_nodes_from(nodes)

    if graph.number_of_nodes() == 0:

        raise RuntimeError(
            f"No network nodes were parsed from:\n{inp_path}"
        )

    if graph.number_of_edges() == 0:

        raise RuntimeError(
            f"No network links were parsed from:\n{inp_path}"
        )

    return graph, inp_path


