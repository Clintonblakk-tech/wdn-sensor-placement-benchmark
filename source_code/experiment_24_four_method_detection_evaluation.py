def save_network_method_bar(
    df: pd.DataFrame,
    metric: str,
    ylabel: str,
    title: str,
    filename: str,
) -> None:

    grouped = (
        df
        .groupby(
            [
                "network",
                "method",
            ]
        )[metric]
        .mean()
        .unstack()
        .reindex(
            index=NETWORKS,
            columns=METHODS,
        )
    )

    ax = grouped.plot(
        kind="bar",
        figsize=(10, 6),
    )

    ax.set_xlabel(
        "Benchmark network"
    )

    ax.set_ylabel(
        ylabel
    )

    ax.set_title(
        title
    )

    plt.xticks(
        rotation=0
    )

    plt.tight_layout()

    plt.savefig(
        FIGURE_DIR / filename,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close()


