def save_method_bar(
    df: pd.DataFrame,
    metric: str,
    ylabel: str,
    title: str,
    filename: str,
) -> None:

    values = (
        df
        .groupby("method")[metric]
        .mean()
        .reindex(METHODS)
    )

    plt.figure(
        figsize=(9, 6)
    )

    plt.bar(
        values.index,
        values.values,
    )

    plt.xlabel(
        "Method"
    )

    plt.ylabel(
        ylabel
    )

    plt.title(
        title
    )

    plt.tight_layout()

    plt.savefig(
        FIGURE_DIR / filename,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close()


