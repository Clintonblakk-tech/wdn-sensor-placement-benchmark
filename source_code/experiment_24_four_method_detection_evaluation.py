# NODE-ID NORMALISATION
# =============================================================================

def normalise_node_id(value) -> str:
    """
    Convert node identifiers to strings while preserving identifiers such as:

        101
        255
        J1208
        J297
    """

    if pd.isna(value):
        return ""

    text = str(value).strip()

    # Handle accidental Excel-style numeric values such as 101.0.
    if text.endswith(".0"):
        numeric_part = text[:-2]

        try:
            float(numeric_part)
            text = numeric_part
        except ValueError:
            pass

    return text


